CREATE TABLE allowed_signup_email_domain (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain varchar(255) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_allowed_signup_email_domain_format
        CHECK (
            domain = btrim(lower(domain))
            and domain !~ '@'
            and domain ~ '^[a-z0-9.-]+$'
        )
);

ALTER TABLE allowed_signup_email_domain ENABLE ROW LEVEL SECURITY;

